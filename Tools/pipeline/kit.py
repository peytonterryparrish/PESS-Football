"""Template-kit pipeline.
Base characters are generated by PixelLab wearing a TEMPLATE kit whose regions have unique hues:
  shirt = blue, shorts = green, socks = red, trim = magenta.
After generation every pixel is snapped: kit pixels -> an exact key colour (region, shade) that the
game's sprite material recolours into any club kit; all other pixels -> the character's own palette.
Key colours (exact, never produced by skin/hair): shirt (v,0,0)? no -- see KEY below."""
import colorsys, json
from PIL import Image

# Template kit fed to PixelLab (natural-looking ramps, 4 shades dark->light)
TEMPLATE = {
    "shirt":  ["#122c5c", "#1c4384", "#2458a8", "#4a7cc8"],
    "shorts": ["#0c4a22", "#136630", "#1e8a3c", "#3caa58"],
    "socks":  ["#5c0a16", "#8e1222", "#ce1831", "#e84c5c"],
    "trim":   ["#5c1a5c", "#8a2a8a", "#c040c0", "#e070e0"],
}
REGION_HUE = {"shirt": 216, "shorts": 140, "socks": 352, "trim": 300}
# Exact key colours written into game frames. Channel layout: R = region code, G = shade, B = 1 marker.
# Region codes 40/80/120/160; shade 64/128/192/255. B=1 never occurs in snapped character palettes (checked in QA).
REGION_CODE = {"shirt": 40, "shorts": 80, "socks": 120, "trim": 160}
SHADES = [64, 128, 192, 255]

def hx(s): s = s.lstrip("#"); return tuple(int(s[i:i + 2], 16) for i in (0, 2, 4))

def hsv(c):
    h, s, v = colorsys.rgb_to_hsv(c[0] / 255, c[1] / 255, c[2] / 255)
    return h * 360, s, v

def hue_d(a, b): d = abs(a - b) % 360; return min(d, 360 - d)

def kit_region(c, min_sat=0.45, max_hue=28):
    """Return region name if colour c is a template-kit colour, else None."""
    h, s, v = hsv(c)
    if s < min_sat or v < 0.12: return None
    best = min(REGION_HUE, key=lambda r: hue_d(h, REGION_HUE[r]))
    if hue_d(h, REGION_HUE[best]) > max_hue: return None
    # red socks vs saturated dark skin/hair: skin hue sits 10-40; socks are 340-360/0-8
    if best == "socks" and not (h >= 335 or h <= 8): return None
    return best

def shade_index(c, region):
    ramp = [hsv(hx(x))[2] for x in TEMPLATE[region]]
    v = hsv(c)[2]
    return min(range(4), key=lambda i: abs(ramp[i] - v))

# ---------- source idle -> template kit ----------
def segment_source(img, kit):
    """img: R08 idle (south) in the PORTSMOUTH-slot HOME kit (blue shirt, white shorts/trim, red socks).
    Hue/saturation rules + body zones (head excluded; white above the waist = trim, below = shorts)."""
    px = img.load(); W, H = img.size
    l, top, r, bot = img.getbbox(); cx = (l + r) / 2
    out = {}
    for y in range(H):
        for x in range(W):
            c = px[x, y]
            if c[3] == 0: continue
            h, s, v = hsv(c[:3])
            f = (y - top) / max(1, bot - top)
            if f < 0.17: continue                      # head and hair
            if s > 0.45 and 195 <= h <= 235: out[(x, y)] = "shirt"
            elif s > 0.55 and (h >= 340 or h <= 6) and f > 0.62: out[(x, y)] = "socks"
            elif s < 0.16 and v > 0.62:
                out[(x, y)] = "trim" if f < 0.41 else ("shorts" if f < 0.70 else "socks_trim")
    return {k: v for k, v in out.items() if v != "socks_trim"}

def to_template(img, kit):
    seg = segment_source(img, kit)
    img = img.copy(); px = img.load()
    # shade by luminance rank within each region
    for (x, y), reg in seg.items():
        v = hsv(px[x, y][:3])[2]
        ramp = TEMPLATE[reg]
        i = 0 if v < 0.30 else 1 if v < 0.50 else 2 if v < 0.78 else 3
        r, g, b = hx(ramp[i]); px[x, y] = (r, g, b, 255)
    return img, seg

# ---------- generated frame -> game frame ----------
def char_palette(img):
    """Non-kit colours of a base character (from its template idle + rotations)."""
    cols = set()
    for c in img.getdata():
        if c[3] > 0 and kit_region(c[:3]) is None: cols.add(c[:3])
    return sorted(cols)

def snap_frame(img, palette, alpha_cut=128):
    """Clamp a generated frame: hard alpha, kit -> key colours, rest -> nearest character palette colour."""
    img = img.convert("RGBA"); px = img.load(); W, H = img.size
    stats = {"kit": 0, "other": 0, "maxdist": 0}
    for y in range(H):
        for x in range(W):
            r, g, b, a = px[x, y]
            if a < alpha_cut: px[x, y] = (0, 0, 0, 0); continue
            reg = kit_region((r, g, b))
            if reg:
                i = shade_index((r, g, b), reg)
                px[x, y] = (REGION_CODE[reg], SHADES[i], 1, 255); stats["kit"] += 1
            else:
                best = min(palette, key=lambda p: (p[0] - r) ** 2 + (p[1] - g) ** 2 + (p[2] - b) ** 2)
                d = ((best[0] - r) ** 2 + (best[1] - g) ** 2 + (best[2] - b) ** 2) ** .5
                stats["maxdist"] = max(stats["maxdist"], d)
                bb = best[2] if best[2] != 1 else 2
                px[x, y] = (best[0], best[1], bb, 255); stats["other"] += 1
    return img, stats

def preview_kit(img, kit):
    """Render a key-coloured game frame in a real kit (python mirror of the UE material, for contact sheets)."""
    img = img.copy(); px = img.load()
    inv = {v: k for k, v in REGION_CODE.items()}
    mult = {64: 0.55, 128: 0.78, 192: 1.0, 255: 1.22}
    for y in range(img.height):
        for x in range(img.width):
            r, g, b, a = px[x, y]
            if a and b == 1 and r in inv:
                base = hx(kit[inv[r]]); m = mult.get(g, 1.0)
                px[x, y] = tuple(min(255, int(c * m)) for c in base) + (255,)
    return img
